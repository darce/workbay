"""Pure proof admission for ignored content; adapters observe the filesystem.

Proof paths are exact repository-relative POSIX paths. Being ignored is never
itself proof of regenerability. No stat, Git invocation, or deletion occurs here.
"""

from pathlib import PurePosixPath


TOOL_CACHE_PRODUCERS = {
    ".pytest_cache": "pytest", ".ruff_cache": "ruff",
    ".mypy_cache": "mypy", "__pycache__": "cpython",
}
TOOL_CACHES = frozenset(TOOL_CACHE_PRODUCERS)
PACKAGE_MANIFESTS = ("pyproject.toml", "setup.cfg")
DEPENDENCY_LOCKFILES = (
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "Cargo.lock", "composer.lock", "Gemfile.lock",
)


def _path_parts(path):
    if not isinstance(path, str) or not path or "\x00" in path or "\\" in path:
        return None
    leaf = PurePosixPath(path)
    if leaf.is_absolute() or ".." in leaf.parts or not leaf.parts:
        return None
    return leaf.parts


def _path_collection(value):
    return isinstance(value, (list, tuple, set, frozenset)) and all(
        _path_parts(path) is not None for path in value
    )


def _tool_cache_proven(path, parts, evidence):
    """Check adapter evidence shape and identity without authenticating it."""
    if not isinstance(evidence, dict) or evidence.get("path") != path:
        return False
    if not any(
        component in TOOL_CACHES
        and evidence.get("cache_root") == str(PurePosixPath(*parts[:index + 1]))
        and evidence.get("producer") == TOOL_CACHE_PRODUCERS[component]
        for index, component in enumerate(parts)
    ):
        return False
    digest = evidence.get("sha256")
    reference = evidence.get("source_ref")
    return (
        evidence.get("coverage") == "complete"
        and isinstance(digest, str) and len(digest) == 64
        and all(character in "0123456789abcdef" for character in digest)
        and isinstance(reference, str) and bool(reference.strip())
    )


def classify_ignored(path, proof):
    """Return ``state``, named ``reason``, and the exact input leaf in ``paths``.

    ``tracked``, ``unchanged`` and ``matching`` are independent adapter proofs:
    a candidate manifest/lockfile must occur in all three. Dependency trees also
    require complete coverage and explicitly empty borrower/reference lists.
    Tool caches require an exact per-request ``tool_cache`` record binding a
    native producer, complete inventory digest and provenance reference.
    Upstream adapters authenticate the native output; this seam checks shape.
    Missing or malformed proof is a typed refusal, never an empty success.
    """
    parts = _path_parts(path)
    result = {"state": "refused", "reason": "ignored_content_unproven", "paths": [path]}
    if parts is None:
        return {**result, "reason": "path_escape"}
    if not isinstance(proof, dict):
        return result

    # A cache name selects the guarded proof class, never proves generated bytes.
    # Refuse here so nested metadata/dependency names cannot bypass cache proof.
    if any(part in TOOL_CACHES for part in parts):
        if _tool_cache_proven(path, parts, proof.get("tool_cache")):
            return {**result, "state": "eligible", "reason": "generated_tool_cache"}
        return result

    if not all(_path_collection(proof.get(key)) for key in ("tracked", "unchanged", "matching")):
        return result
    proven = set(proof["tracked"]) & set(proof["unchanged"]) & set(proof["matching"])
    for index, component in enumerate(parts):
        parent = PurePosixPath(*parts[:index])
        if component.endswith((".egg-info", ".dist-info")) and any(
            str(parent / name) in proven for name in PACKAGE_MANIFESTS
        ):
            return {**result, "state": "eligible", "reason": "generated_build_metadata"}
        if component in ("node_modules", "vendor") and (
            proof.get("dependency_coverage") == "complete"
            and proof.get("borrowers") == []
            and proof.get("references") == []
            and any(str(parent / name) in proven for name in DEPENDENCY_LOCKFILES)
        ):
            return {**result, "state": "eligible", "reason": "generated_dependency_tree"}
    return result
