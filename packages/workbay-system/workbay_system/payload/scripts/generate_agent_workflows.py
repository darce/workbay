def _render_claude_command(command: dict, manifest: dict) -> str:
    """Render a Claude plugin slash command that routes to its canonical skill."""
    return _render_prompt_with_guidance(command, None, manifest)


def _extract_markdown_section(body: str, heading: str) -> str | None:
    lines = body.splitlines()
    marker = f"## {heading}"
    start: int | None = None

    for index, line in enumerate(lines):
        if line.strip() == marker:
            start = index
            break

    if start is None:
        return None

    end = len(lines)
    for index in range(start + 1, len(lines)):
        if lines[index].startswith("## "):
            end = index
            break

    return "\n".join(lines[start:end]).strip()


def _extract_prompt_guidance(structured: dict, body: str) -> str | None:
    _, generator = _strip_generator_metadata(structured)
    requested_sections = generator.get("prompt_body_sections") or []
    if not isinstance(requested_sections, list):
        requested_sections = []

    # VS Code Copilot does not consume the Claude/Codex plugin tree, so
    # its generated prompt must carry the canonical skill implementation
    # by default. Individual skills can keep prompts smaller by declaring
    # generator.prompt_body_sections in skill.yaml.
    if not requested_sections:
        return body.strip() or None

    sections: list[str] = []
    for heading in requested_sections:
        if not isinstance(heading, str) or not heading.strip():
            continue
        section = _extract_markdown_section(body, heading.strip())
        if section:
            sections.append(section)

    if not sections:
        return None
    return "\n\n".join(sections)


def _render_tombstone_row(command: dict, live_ids: set[str]) -> str:
    """Router row for a retired id; it stays listed even when its redirect is gone.

    The source manifest always names a live replacement, so an absent one
    means a local override disabled the skill behind it: say so rather than
    redirect to a command that no longer exists.
    """
    replacement = _replacement_command_id(command)
    if replacement in live_ids:
        return f"- `/{command['command_id']}` → use `/{replacement}`"
    return f"- `/{command['command_id']}` → removed by local override"


def _render_codex_router_body(
    manifest: dict,
    *,
    manifest_rel: str = _DEFAULT_MANIFEST_REL,
    generator_rel: str = _DEFAULT_GENERATOR_REL,
) -> list[str]:
    commands: list[dict] = _live_commands(manifest)
    tombstones: list[dict] = _tombstone_commands(manifest)
    managed_ids = ", ".join(f"`/{command['command_id']}`" for command in commands)
    live_ids = {command["command_id"] for command in commands}
    lines = [
        *_render_global_instructions(manifest),
        (
            "If a user prompt begins with a registered `/command_id`, treat that prefix as a portable workflow "
            f"command routed through `{manifest_rel}`."
        ),
        "",
        f"Current managed ids: {managed_ids}.",
        "",
        "Routing rules:",
        "",
        "- Strip the leading `/command_id` token before normal intent analysis.",
        "- Load the mapped skill from the manifest and use its `makefile_target` as the primary entry point when one exists.",
        "- Interpret the remainder of the user message using the manifest-defined argument names.",
        (
            "- If generated adapters drift from the manifest, run `make generate-agent-workflows`; "
            "`make check-agent-workflows` verifies Claude, VS Code, and Codex outputs together. "
            f"Regenerate from `{generator_rel}`."
        ),
        "",
        "Command map:",
        "",
        *(
            f"- `/{command['command_id']}` ({command['mode']}) -> skill `{command['skill']}` -> `{command['makefile_target']}`"
            for command in commands
        ),
    ]
    if tombstones:
        lines.extend(
            [
                "",
                "Retired ids are fail-closed discovery metadata, never resolvable commands. "
                "Do not execute them, do not substitute a live workflow, and do not publish "
                "`/wb-tombstone` as a slash command. Redirect from the `replaces` field:",
                "",
                *(_render_tombstone_row(command, live_ids) for command in tombstones),
            ]
        )
    return lines


