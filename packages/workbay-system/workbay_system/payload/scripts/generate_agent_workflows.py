# harness-protocol.yaml. The per-harness JSON configs are generated goldens:
#   .github/hooks/terminal-guard.json  (VS Code / Copilot runner)
#   .codex/hooks.json                  (Codex CLI)
# Codex handlers carry `statusMessage` (rendered from the contract's
# harness-neutral `status_message`) so its UI names hooks instead of showing
# "Hook 1 / Hook 2"; the VS Code runner has no display field yet, so the value
# is omitted there. The contract-derived Claude hooks block is generated as
# ``.claude/settings.hooks.json`` (hooks subtree only); wholesale
# ``.claude/settings.json`` composition lands in internal.

_HOOKS_CONTRACT_RELATIVE = HARNESS_CONTRACT_RELPATH  # SSOT (workbay_protocol.paths)
_HOOK_STAGE_KEYS: tuple[tuple[str, str], ...] = (
    ("pre_tool_use", "PreToolUse"),
    ("post_tool_use", "PostToolUse"),
    ("session_start", "SessionStart"),
    ("user_prompt_submit", "UserPromptSubmit"),
)
# PostToolUse uses the nested matcher+hooks[] grouping (the Claude-schema shape
# both runners already accept for it); the other stages stay flat.
_NESTED_HOOK_STAGES = frozenset({"post_tool_use"})
_DEFAULT_HOOK_TIMEOUT = 5


def _require_codex_optout(item: dict, stage: str) -> None:
    """Enforce the documented Codex opt-out: an entry may omit ``codex_command``
    only when it declares ``codex_enabled: false`` plus a non-empty
    ``unsupported_reason`` — silent omission leaves no audit trail for why a
    hook is absent from ``.codex/hooks.json``."""
    reason = item.get("unsupported_reason")
    if (
        item.get("codex_enabled") is not False
        or not isinstance(reason, str)
        or not reason.strip()
    ):
        raise ValueError(
            f"hook `{item.get('id')}` ({stage}) omits `codex_command`; a "
            "Codex-skipped hook must declare `codex_enabled: false` and a "
            "non-empty `unsupported_reason`"
        )


# internal: fail-open wrapper injection. Every rendered tool-guard
# command is prefixed with the payload wrapper so a missing/unspawnable
# handler exits 0 (with hook_infra_failure telemetry) instead of fail-closing
# the harness. Contract entries may opt out of fail-open via
# ``fail_mode: closed`` (rendered as --fail-mode=closed; the wrapper then
# blocks on a missing handler). The transform lives in the stdlib-only
# sibling module ``_guard_wrap.py`` so ``check_harness_sync.py`` can import
# the SAME implementation without this module's pydantic dependency.


def _load_guard_wrap_module():
    import importlib.util

    path = Path(__file__).resolve().parent / "_guard_wrap.py"
    spec = importlib.util.spec_from_file_location("_payload_guard_wrap", path)
    if spec is None or spec.loader is None:  # pragma: no cover - ships together
        raise SystemExit(f"missing payload module {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_maybe_reexec_hoisted_copy()
_guard_wrap_module = _load_guard_wrap_module()
_wrap_guard_command = _guard_wrap_module.wrap_guard_command
_anchor_to_repo_root = _guard_wrap_module.anchor_to_repo_root


def _render_hooks_config(
    hooks_spec: dict,
    *,
    command_key: str,
    matcher_key: str,
    include_status_message: bool,
    enforce_codex_optout: bool = False,
    nested_stages: frozenset[str] = _NESTED_HOOK_STAGES,
    anchor_commands: bool = False,
) -> dict:
    config: dict[str, list[dict]] = {}
    for stage, config_stage in _HOOK_STAGE_KEYS:
        entries: list[dict] = []
        for item in hooks_spec.get(stage) or []:
            command = item.get(command_key)
            # strip-normalized so renderer and check_harness_sync classify a
            # whitespace-only command identically (omitted, not present).
            if not isinstance(command, str) or not command.strip():
                if enforce_codex_optout:
                    _require_codex_optout(item, stage)
                continue
            if enforce_codex_optout and item.get("codex_enabled") is False:
                raise ValueError(
                    f"hook `{item.get('id')}` ({stage}) declares "
                    "`codex_enabled: false` but still sets `codex_command`; "
                    "drop one of the two"
                )
            handler: dict = {
                "type": "command",
                "command": _wrap_guard_command(
                    command, fail_mode=item.get("fail_mode")
                ),
                "timeout": int(item.get("timeout", _DEFAULT_HOOK_TIMEOUT)),
            }
            if anchor_commands:
                handler["command"] = _anchor_to_repo_root(handler["command"])
            if include_status_message:
                status_message = item.get("status_message")
                if not isinstance(status_message, str) or not status_message.strip():
                    raise ValueError(
                        f"hook `{item.get('id')}` ({stage}) is missing the non-empty "
                        "`status_message` required to render Codex statusMessage"
                    )
                handler["statusMessage"] = status_message
            matcher = item.get(matcher_key, item.get("matcher"))
            if stage in nested_stages:
                entry = {}
                if matcher is not None:
                    entry["matcher"] = matcher
                entry["hooks"] = [handler]
                entries.append(entry)
            else:
                entry: dict = {}
                if matcher is not None:
                    entry["matcher"] = matcher
                entry.update(handler)
                entries.append(entry)
        config[config_stage] = entries
    return {"hooks": config}


def render_vscode_hooks_config(hooks_spec: dict) -> dict:
    return _render_hooks_config(
        hooks_spec,
        command_key="vscode_command",
        matcher_key="vscode_matcher",
        include_status_message=False,
    )


def render_composed_claude_settings_hooks(
    hooks_spec: dict,
    *,
    override_root: Path | None = None,
    override_manifest: Any | None = None,
) -> dict:
    """Render contract hooks, optionally composing consumer overrides."""
    base = render_claude_hooks_config(hooks_spec)
    if override_root is None or override_manifest is None:
        return base
    from workbay_protocol.bootstrap import PluginOverrideManifest

    # Coerce BEFORE touching attributes: the signature accepts a raw mapping
    # (e.g. the dict loaded from overrides.yaml), which has no `.components`.
    if not isinstance(override_manifest, PluginOverrideManifest):
        override_manifest = PluginOverrideManifest.model_validate(override_manifest)
    if not override_manifest.components.claude_settings_hooks:
        return base
    compose = _import_plugin_override_compose()
    composed_stages, _components = compose.compose_claude_settings_hooks_overrides(
        base["hooks"],
        override_root,
        override_manifest,
    )
    return {"hooks": composed_stages}


def render_claude_hooks_config(hooks_spec: dict) -> dict:
    """Render the contract-derived hooks block for Claude settings.

    Claude Code requires every stage entry to carry nested ``hooks[]`` with a
    ``matcher`` (empty string when the contract omits one). Legacy commands stay
    RAW so ``check_harness_sync`` membership stays aligned with
    ``claude_command`` literals (implementation note / internal). Entries with
    ``fail_mode: closed`` are policy-aware wrapped — a raw flag does not
    implement blocking (implementation note C3). The wrap is idempotent on an already
    wrapped command.
    """
    config: dict[str, list[dict]] = {}
    for stage, config_stage in _HOOK_STAGE_KEYS:
        entries: list[dict] = []
        for item in hooks_spec.get(stage) or []:
            command = item.get("claude_command")
            if not isinstance(command, str) or not command.strip():
                continue
            fail_mode = item.get("fail_mode")
            if fail_mode == "closed":
                command = _wrap_guard_command(command, fail_mode=fail_mode)
            matcher = item.get("claude_matcher", item.get("matcher"))
            if matcher is None:
                matcher = ""
            entries.append(
                {
                    "matcher": matcher,
                    "hooks": [
                        {
                            "type": "command",
                            "command": command,
                            "timeout": int(item.get("timeout", _DEFAULT_HOOK_TIMEOUT)),
                        }
                    ],
                }
            )
        config[config_stage] = entries
    return {"hooks": config}


def render_codex_hooks_config(hooks_spec: dict) -> dict:
    # The codex_enabled opt-out contract only binds codex-aware contracts (any
    # entry carrying codex_command / codex_enabled). A legacy contract that
    # pre-dates the Codex fields entirely (e.g. a stale consumer mirror) keeps
    # the old skip-silently rendering instead of hard-failing generation.
    codex_aware = any(
        "codex_command" in item or "codex_enabled" in item
        for stage, _ in _HOOK_STAGE_KEYS
        for item in hooks_spec.get(stage) or []
    )
    return _render_hooks_config(
        hooks_spec,
        command_key="codex_command",
        matcher_key="codex_matcher",
        include_status_message=True,
        enforce_codex_optout=codex_aware,
        nested_stages=frozenset(stage for stage, _ in _HOOK_STAGE_KEYS),
        anchor_commands=True,
    )


