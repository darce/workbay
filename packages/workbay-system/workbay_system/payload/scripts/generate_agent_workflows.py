_EXIT_CONTRADICTORY_OVERRIDE = 3


class ContradictoryPluginOverride(SystemExit):
    """An override adds a portable command routed to a skill it also disables.

    Generation refuses: dropping the added command silently or resurrecting
    the disabled skill would each ignore half of the override. The distinct
    exit status lets callers branch without parsing the message [AGT-21].
    """

    def __init__(self, override_manifest: Path, command_id: str, skill: str) -> None:
        self.command_id = command_id
        self.skill = skill
        self.message = (
            f"{override_manifest}: contradictory override: "
            f"components.portable_commands.{command_id} adds command {command_id!r} "
            f"routed to skill {skill!r}, but components.skills.{skill} disables that skill"
        )
        super().__init__(_EXIT_CONTRADICTORY_OVERRIDE)

    def __str__(self) -> str:
        return self.message


class EffectiveComposition(NamedTuple):
    """The one effective skill composition every adapter reads.

    ``manifest`` keeps tombstone rows plus only the live commands whose skill
    survived composition (base and override-added). ``rendered_skills`` maps
    every surviving slug, in emission order, to its composed plugin SKILL.md
    text. ``prompt_sources`` holds the ``(structured, body)`` pair each live
    command's Copilot prompt renders from: canonical source for untouched
    skills, the composed text for replaced, patched, or added ones. A patch
    merges in projected link space; ``link_resources`` names the workspace
    resources the base tree and that projection resolved, so kept links in
    any override copied from the emitted tree stay bundled.
    """

    manifest: dict
    rendered_skills: dict[str, str]
    prompt_sources: dict[str, tuple[dict, str]]
    disabled_slugs: frozenset[str]
    skill_components: list[dict[str, str]]
    command_components: list[dict[str, str]]
    override_payload: PluginOverrideManifest | None
    link_resources: dict[PurePosixPath, tuple[str, Path]]


def _skill_md_body(text: str) -> str:
    """Body of a SKILL.md text, without parsing (or trusting) its frontmatter."""
    if text.startswith("---"):
        parts = text.split("---", 2)
        if len(parts) == 3:
            return parts[2].lstrip("\n")
    return text


def _refuse_contradictory_command_overrides(
    override_root: Path, payload: PluginOverrideManifest, disabled: frozenset[str]
) -> None:
    compose = _import_plugin_override_compose()
    for command_id, override in sorted(payload.components.portable_commands.items()):
        if override.mode != "add":
            continue
        # Same reader (and override-root escape guard) the composer uses.
        command = compose._read_override_portable_command(override_root, override.path)
        skill = command.get("skill")
        if skill in disabled:
            raise ContradictoryPluginOverride(
                override_root / _PLUGIN_OVERRIDE_MANIFEST, command_id, skill
            )


def _recognize_projected_upstream_digests(
    payload: PluginOverrideManifest,
    rendered_skills: dict[str, str],
    skills_source_root: Path,
) -> PluginOverrideManifest:
    """Accept a replace digest recorded against the emitted base SKILL.md.

    Overrides compose on the unprojected rendering, but consumer tooling
    (``overrides accept-upstream`` / ``relock``) hashes the emitted base tree,
    whose links are projected. Both digests name the same upstream, so a
    replace digest matching the base projection is mapped to the composer's.
    Patch digests pin the stored fork copy and need no mapping.
    """
    replaces = {
        slug
        for slug, override in payload.components.skills.items()
        if override.mode == "replace"
        and slug in rendered_skills
        and override.upstream_digest != _sha256_digest(rendered_skills[slug])
    }
    if not replaces:
        return payload
    base_projection, _ = _project_plugin_links(
        rendered_skills, skills_source_root, frozenset()
    )
    payload = payload.model_copy(deep=True)
    for slug in replaces:
        override = payload.components.skills[slug]
        if override.upstream_digest == _sha256_digest(base_projection[slug]):
            override.upstream_digest = _sha256_digest(rendered_skills[slug])
    return payload


def _effective_composition(
    manifest: dict,
    skills_source_root: Path,
    override_root: Path | None = None,
    harness_protocol: dict | None = None,
) -> EffectiveComposition:
    """Compose skill and portable-command overrides once for every adapter.

    The plugin tree (skills, Claude commands, lock) and the legacy adapters
    (Copilot prompts, Codex router) all read this result. Canonical skills
    load only here, before composition; a slug the override disables is never
    loaded again, and any live command routed to it leaves ``manifest``.
    """
    _validate_command_skill_sources(manifest, skills_source_root)
    canonical: dict[str, tuple[dict, str]] = {}
    rendered: dict[str, str] = {}
    for command in _live_commands(manifest):
        slug = command["skill"]
        if slug in canonical:
            continue
        canonical[slug] = _load_skill(skills_source_root, slug)
        # Only a body carrying the routing marker needs the harness contract.
        if harness_protocol is None and _HARNESS_ROUTING_BEGIN in canonical[slug][1]:
            harness_protocol = _load_harness_protocol()
        rendered[slug] = _render_plugin_skill(
            *canonical[slug], manifest, harness_protocol
        )

    payload: PluginOverrideManifest | None = None
    disabled: frozenset[str] = frozenset()
    skill_components: list[dict[str, str]] = []
    command_components: list[dict[str, str]] = []
    overridden: dict[str, str] = {}
    link_resources: dict[PurePosixPath, tuple[str, Path]] = {}
    if override_root is not None:
        payload = _load_plugin_override_manifest(override_root)
        overridden = {
            slug: override.mode for slug, override in payload.components.skills.items()
        }
        disabled = frozenset(
            slug for slug, mode in overridden.items() if mode == "disable"
        )
        _refuse_contradictory_command_overrides(override_root, payload, disabled)
        # Every workspace resource the base tree bundles is a valid kept link
        # for an override copied from it (replace and add included).
        _project_plugin_links(
            rendered, skills_source_root, frozenset(), resources=link_resources
        )

        # The emitted skill set: a sibling-skill link merges as
        # ../<slug>/SKILL.md, the form the emitted tree uses.
        emitted_skills = {slug: "" for slug in rendered if slug not in disabled}
        emitted_skills.update(
            {slug: "" for slug, mode in overridden.items() if mode == "add"}
        )

        def link_space(slug: str, text: str) -> str:
            # A fork copied from the emitted SKILL.md is projected; the
            # upstream rendering is not. All merge inputs pass through here.
            projected, _ = _project_plugin_links(
                {**emitted_skills, slug: text},
                skills_source_root,
                disabled,
                resources=link_resources,
            )
            return projected[slug]

        composed, skill_order, skill_components = _compose_plugin_skill_overrides(
            rendered,
            override_root,
            _recognize_projected_upstream_digests(payload, rendered, skills_source_root),
            link_space=link_space,
        )
        rendered = {slug: composed[slug] for slug in skill_order}
        if payload.components.portable_commands:
            manifest, command_components = _compose_plugin_portable_command_overrides(
                manifest, override_root, payload, composed_skills=rendered
            )

    manifest = {
        **manifest,
        "commands": [
            command
            for command in manifest["commands"]
            if _is_tombstone(command) or command["skill"] in rendered
        ],
    }
    prompt_sources: dict[str, tuple[dict, str]] = {}
    for command in _live_commands(manifest):
        slug = command["skill"]
        if slug in prompt_sources:
            continue
        mode = overridden.get(slug)
        if mode is None:
            prompt_sources[slug] = canonical[slug]
            continue
        # Composed text is plugin SKILL.md shape: the prompt needs its body.
        # A patch merges into the canonical rendering, so the canonical
        # prompt-section hints still name sections that body carries.
        structured: dict = {}
        if mode == "patch":
            structured["generator"] = canonical[slug][0].get("generator") or {}
        prompt_sources[slug] = (structured, _skill_md_body(rendered[slug]))
    return EffectiveComposition(
        manifest=manifest,
        rendered_skills=rendered,
        prompt_sources=prompt_sources,
        disabled_slugs=disabled,
        skill_components=skill_components,
        command_components=command_components,
        override_payload=payload,
        link_resources=link_resources,
    )


_MARKDOWN_LINK_RE = re.compile(r"\]\(([^)\s]+)\)")
_URL_SCHEME_RE = re.compile(r"[A-Za-z][A-Za-z0-9+.-]*:")
_SKILL_NAME = r"[A-Za-z0-9][A-Za-z0-9._-]*"
# A skill body links a sibling skill as ``../<slug>/body.md`` (source layout)
# or ``../<slug>/SKILL.md``; any document may name ``skills/<slug>/...``.
_SIBLING_SKILL_LINK_RE = re.compile(rf"\.\./({_SKILL_NAME})/(?:body|SKILL)\.md")
_SKILL_LINK_RES = (
    re.compile(rf"(?:.*/)?skills/({_SKILL_NAME})/(?:body|SKILL)\.md"),
    re.compile(rf"(?:.*/)?references/source-skills/({_SKILL_NAME})\.md"),
)
_SOURCE_SKILL_REFS = PurePosixPath("references/source-skills")
_WORKSPACE_REFS = PurePosixPath("references/workspace")


def _source_skill_reference_text(slug: str, *, disabled: bool) -> str:
    reason = (
        "is disabled by the effective plugin override composition"
        if disabled
        else "is not emitted in this plugin tree, so its guidance is unavailable here"
    )
    return (
        f"# Source skill: {slug}\n\n"
        f"Source skill `{slug}` {reason}. This generated reference is not a "
        "callable native skill or slash command and carries no replacement "
        "guidance. Do not substitute another workflow for it; if the step needs "
        f"`{slug}`, stop and report the missing input.\n"
    )


def _workspace_stub_text(logical: str) -> str:
    return (
        f"# Workspace resource: {logical}\n\n"
        f"`{logical}` is not bundled with this plugin tree. Read `{logical}` in "
        "the consumer workspace. If it is unavailable there, stop and report "
        "the missing input; this generated reference supplies no replacement "
        "policy.\n"
    )


def _bundled_file_text(logical: str, text: str) -> str:
    longest = max((len(run) for run in re.findall(r"`+", text)), default=0)
    fence = "`" * max(3, longest + 1)
    body = text if text.endswith("\n") else text + "\n"
    return (
        f"# Workspace resource: {logical}\n\n"
        f"Bundled copy of `{logical}` from the WorkBay payload.\n\n"
        f"{fence}\n{body}{fence}\n"
    )


def _resolve_workspace_resource(
    link_path: str, origin: Path, payload_root: Path
) -> tuple[str, Path | None]:
    """Map a source-relative link to ``(logical payload path, file or None)``.

    Only files inside the payload resolve; the logical path never carries a
    machine path. Skill bodies use docs-relative shorthand
    (``../../instructions.md``, ``rules/...``, ``playbooks/...``) for
    ``docs/workbay/``.
    """
    literal = (origin.parent / link_path).resolve()
    if literal.is_relative_to(payload_root) and literal.is_file():
        return literal.relative_to(payload_root).as_posix(), literal
    logical = posixpath.normpath(re.sub(r"^(?:\.\.?/)+", "", link_path))
    if logical == "instructions.md" or logical.startswith(("rules/", "playbooks/")):
        logical = f"docs/workbay/{logical}"
    candidate = (payload_root / logical).resolve()
    if candidate.is_relative_to(payload_root) and candidate.is_file():
        return candidate.relative_to(payload_root).as_posix(), candidate
    return logical, None


def _project_plugin_links(
    rendered_skills: dict[str, str],
    skills_source_root: Path,
    disabled_slugs: frozenset[str],
    *,
    resources: dict[PurePosixPath, tuple[str, Path]] | None = None,
) -> tuple[dict[str, str], dict[PurePosixPath, str]]:
    """Retarget source-relative links so emitted plugin skills resolve.

    Returns ``(projected SKILL.md text by slug, references by path)``, both
    relative to a harness root. A link to another skill becomes
    ``../<slug>/SKILL.md`` when that skill is emitted, else a generated
    ``references/source-skills/<slug>.md`` that says the source is disabled
    or unavailable (never a reload of its body). A workspace resource is
    bundled under ``references/workspace/<name>.<hash16>.md`` when the payload
    has it, else stubbed with read-in-workspace-or-stop guidance; the hash is
    of the logical relative path. URL-scheme and ``#fragment``-only links are
    untouched, and already-projected links are kept, so composer-owned bytes
    forked from an emitted tree project idempotently.

    ``resources`` records each workspace reference's ``(link, origin)``; a
    kept link it names is bundled again rather than stubbed (patch merges
    run in projected space, so their kept links came from the source).
    """
    payload_root = skills_source_root.parent.resolve()
    references: dict[PurePosixPath, str] = {}
    kept_references: set[PurePosixPath] = set()

    def link(destination: PurePosixPath, target: PurePosixPath, fragment: str) -> str:
        return posixpath.relpath(target.as_posix(), destination.parent.as_posix()) + fragment

    def skill_target(slug: str) -> PurePosixPath:
        if slug in rendered_skills:
            return PurePosixPath("skills", slug, "SKILL.md")
        target = _SOURCE_SKILL_REFS / f"{slug}.md"
        references.setdefault(
            target,
            _source_skill_reference_text(slug, disabled=slug in disabled_slugs),
        )
        return target

    def resource_target(link_path: str, origin: Path) -> PurePosixPath:
        logical, source = _resolve_workspace_resource(link_path, origin, payload_root)
        digest = hashlib.sha256(logical.encode("utf-8")).hexdigest()[:16]
        name = PurePosixPath(logical).name or "resource"
        target = _WORKSPACE_REFS / f"{name}.{digest}.md"
        if resources is not None:
            resources.setdefault(target, (link_path, origin))
        if target in references:
            return target
        references[target] = ""  # claim first: bundled docs may link back
        if source is None:
            references[target] = _workspace_stub_text(logical)
            return target
        try:
            text = source.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            references[target] = _workspace_stub_text(logical)
            return target
        if source.suffix == ".md":
            references[target] = project(text, target, source)
        else:
            references[target] = _bundled_file_text(logical, text)
        return target

    def project(text: str, destination: PurePosixPath, origin: Path) -> str:
        in_skill = destination.parts[0] == "skills"

        def replace(match: re.Match[str]) -> str:
            value = match.group(1)
            if value.startswith("#") or _URL_SCHEME_RE.match(value):
                return match.group(0)
            link_path, separator, anchor = value.partition("#")
            fragment = separator + anchor
            patterns = (
                (_SIBLING_SKILL_LINK_RE, *_SKILL_LINK_RES) if in_skill else _SKILL_LINK_RES
            )
            for pattern in patterns:
                skill_link = pattern.fullmatch(link_path)
                if skill_link:
                    target = skill_target(skill_link.group(1))
                    return f"]({link(destination, target, fragment)})"
            in_tree = PurePosixPath(
                posixpath.normpath(posixpath.join(destination.parent.as_posix(), link_path))
            )
            if in_skill and in_tree.parent == _WORKSPACE_REFS:
                kept_references.add(in_tree)
                return match.group(0)
            target = resource_target(link_path, origin)
            return f"]({link(destination, target, fragment)})"

        return _MARKDOWN_LINK_RE.sub(replace, text)

    projected = {
        slug: project(
            text,
            PurePosixPath("skills", slug, "SKILL.md"),
            skills_source_root / slug / "body.md",
        )
        for slug, text in rendered_skills.items()
    }
    missing = sorted(kept_references - set(references))
    for target in missing:
        if resources is not None and target in resources:
            resource_target(*resources[target])
    for target in missing:
        if target in references:
            continue
        references[target] = (
            f"# Workspace resource: {target.name}\n\n"
            "This generated reference is not produced from the current source "
            "snapshot. Regenerate the override from the current base plugin "
            "tree, or stop and report the missing input.\n"
        )
    return projected, references


def _portable_command_digest(command: dict) -> str:
    return _sha256_digest(json.dumps(command, sort_keys=True, ensure_ascii=False))


# Add-only receipt keys (FU-153-5), set only on override entries. Unset, they
# are omitted, so a lock with no override root keeps its bytes.
_PROJECTED_LOCK_KEYS = ("current_base_projected_digest", "effective_projected_digest")


def _render_plugin_effective_lock_json(
    base_remote_sha: str,
    effective_root: Path,
    components: list[dict[str, str]],
) -> str:
    if len(base_remote_sha) != 40 or any(
        ch not in "0123456789abcdef" for ch in base_remote_sha
    ):
        raise SystemExit(
            f"--plugin-base-remote-sha must be a 40-char lowercase git SHA; found {base_remote_sha!r}"
        )
    payload = PluginEffectiveLock.model_validate(
        {
            "schema_version": 1,
            "plugin": _PLUGIN_NAME,
            "base_remote_sha": base_remote_sha,
            "effective_root": ".",
            "components": components,
        }
    ).model_dump(mode="json")
    for entry in payload["components"]:
        for key in _PROJECTED_LOCK_KEYS:
            if entry[key] is None:
                del entry[key]
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


def _override_digest_note(entry: dict) -> str:
    """``(recorded X vs current Y, <space>)`` for a stale or conflicted entry.

    Bootstrap ``overrides relock`` / ``accept-upstream`` record the projected
    emitted SKILL.md, so the recorded digest is compared with the projected
    current base. Only a recorded digest equal to the composer's unprojected
    rendering, or a receipt without the projected key, is compared in
    composer space.
    """
    recorded = entry.get("recorded_upstream_digest")
    projected = entry.get("current_base_projected_digest")
    if projected is not None and recorded != entry.get("current_base_digest"):
        return f"(recorded {recorded} vs current {projected}, projected space)"
    return (
        f"(recorded {recorded} vs current {entry.get('current_base_digest')}, "
        "composer space)"
    )


def _expected_plugin_outputs(
    manifest: dict,
    mcp_manifest: dict,
    skills_source_root: Path,
    plugin_out: Path,
    plugin_overrides: Path | None = None,
    plugin_base_remote_sha: str | None = None,
    plugin_passthrough_lock: bool = False,
    harness_protocol: dict | None = None,
) -> tuple[dict[Path, str], list[str]]:
    """Map every emitted plugin-tree file to its rendered content.

    Layout per harness::

        <plugin_out>/<harness>/<plugin_dir>/plugin.json
        <plugin_out>/<harness>/.mcp.json   (only under `registration: plugin`)
        <plugin_out>/claude/commands/<command_id>.md
        <plugin_out>/<harness>/skills/<slug>/SKILL.md
        <plugin_out>/<harness>/references/{source-skills,workspace}/*.md

    Every surface reads one ``_effective_composition``; ``references/`` holds
    the link targets ``_project_plugin_links`` generates for skill bodies.
    """
    outputs: dict[Path, str] = {}
    audit_lines: list[str] = []
    plugin_version = mcp_manifest["plugin_version"]
    registration = mcp_manifest["registration"]
    if harness_protocol is None:
        harness_protocol = _load_harness_protocol()

    if plugin_overrides is not None and plugin_passthrough_lock:
        raise SystemExit(
            "--plugin-passthrough-lock cannot be combined with --plugin-overrides"
        )
    if plugin_overrides is not None and plugin_base_remote_sha is None:
        raise SystemExit(
            "--plugin-base-remote-sha is required when --plugin-overrides is set"
        )
    # Plugin harnesses discover slash commands from skills/<slug>/. Live
    # rows therefore emit under the canonical skill slug, not command_id.
    # The wb-* rail is router/prompt-only on this surface (Codex router +
    # Copilot prompts). Tombstones stay fail-closed metadata and are not
    # published as slash-discoverable directories. See plugin-distribution.md.
    effective = _effective_composition(
        manifest, skills_source_root, plugin_overrides, harness_protocol
    )
    manifest = effective.manifest
    rendered_skills = effective.rendered_skills
    effective_components: list[dict[str, str]] = list(effective.skill_components)
    if plugin_overrides is not None:
        override_payload = effective.override_payload
        mcp_manifest, mcp_components, audit_lines = _compose_plugin_mcp_overrides(
            mcp_manifest,
            plugin_overrides,
            override_payload,
        )
        effective_components.extend(mcp_components)
        effective_components.extend(effective.command_components)
        if override_payload.components.claude_settings_hooks:
            # iter4-g: claude_settings_hooks overrides compose into the managed
            # .claude/settings.json hooks. Record each as an effective-lock
            # component (parity with skill / mcp_server / portable_command) so
            # doctor/repair can detect drift on a consumer settings-hook
            # override. The compose fn already builds the per-component digest;
            # render_composed_claude_settings_hooks previously discarded it.
            base_claude_hooks = render_claude_hooks_config(
                harness_protocol.get("hooks") or {}
            )["hooks"]
            compose = _import_plugin_override_compose()
            _composed_hooks, settings_hook_components = (
                compose.compose_claude_settings_hooks_overrides(
                    base_claude_hooks,
                    plugin_overrides,
                    override_payload,
                )
            )
            effective_components.extend(settings_hook_components)
    elif plugin_passthrough_lock:
        # internal always-effective: a zero-override effective tree is the base
        # tree composed unchanged; the lock receipt records every component as
        # passthrough so doctor/repair can distinguish "composed clean" from
        # "never composed".
        if plugin_base_remote_sha is None:
            raise SystemExit(
                "--plugin-base-remote-sha is required when --plugin-passthrough-lock is set"
            )
        effective_components = [
            {
                "component_kind": "skill",
                "name": slug,
                "mode": "passthrough",
                "effective_digest": _sha256_digest(text),
            }
            for slug, text in rendered_skills.items()
        ]
        effective_components.extend(
            {
                "component_kind": "mcp_server",
                "name": server["name"],
                "mode": "passthrough",
                "effective_digest": _canonical_mcp_server_digest(server),
            }
            for server in mcp_manifest["mcp_servers"]
        )
        effective_components.extend(
            {
                "component_kind": "portable_command",
                "name": command["command_id"],
                "mode": "passthrough",
                "effective_digest": _portable_command_digest(command),
            }
            for command in _live_commands(manifest)
        )

    projected_skills, references = _project_plugin_links(
        rendered_skills,
        skills_source_root,
        effective.disabled_slugs,
        resources=dict(effective.link_resources),
    )
    if plugin_overrides is not None:
        # An override entry also names the bytes it emits (the projected
        # SKILL.md an operator forks); ``effective_digest`` stays composer's.
        effective_components = [
            {
                **component,
                "effective_projected_digest": _sha256_digest(
                    projected_skills[component["name"]]
                ),
            }
            if component["component_kind"] == "skill"
            and component["name"] in projected_skills
            else component
            for component in effective_components
        ]
    grok_hooks_body = _render_grok_plugin_hooks_json(harness_protocol)
    cursor_hooks_body = render_hooks_config_text(
        render_cursor_hooks_config(harness_protocol.get("hooks") or {})
    )

    for harness, plugin_dir in _PLUGIN_HARNESSES:
        harness_root = plugin_out / harness
        plugin_owns_mcp = registration[harness] == "plugin"
        outputs[harness_root / plugin_dir / "plugin.json"] = (
            _render_plugin_manifest_json(
                plugin_version,
                include_mcp_servers=plugin_owns_mcp,
                include_commands=harness == "claude",
            )
        )
        if plugin_owns_mcp:
            outputs[harness_root / ".mcp.json"] = _render_mcp_servers_json(
                mcp_manifest, harness
            )
        if harness == "grok":
            outputs[harness_root / "hooks" / "hooks.json"] = grok_hooks_body
        if harness == "cursor":
            outputs[harness_root / "hooks.json"] = cursor_hooks_body
            # Skills-only surface: a single marker in place of per-command
            # markdown so Cursor does not show duplicate workflow picker entries.
            outputs[harness_root / "commands" / _CURSOR_SKILLS_ONLY_MARKER_NAME] = (
                _CURSOR_COMMANDS_SKILLS_ONLY_MARKER
            )
        if harness == "claude":
            # ``manifest`` is the effective one: a command whose skill the
            # composition disabled has no row here, so no dangling route.
            for command in _live_commands(manifest):
                outputs[
                    harness_root / "commands" / f"{command['command_id']}.md"
                ] = _render_claude_command(command, manifest)
        for slug, text in projected_skills.items():
            outputs[harness_root / "skills" / slug / "SKILL.md"] = text
        for relative, text in references.items():
            outputs[harness_root / relative] = text
    if plugin_overrides is not None or plugin_passthrough_lock:
        outputs[plugin_out / _PLUGIN_EFFECTIVE_LOCK] = (
            _render_plugin_effective_lock_json(
                plugin_base_remote_sha,
                plugin_out,
                effective_components,
            )
        )
    return outputs, audit_lines


def _extra_plugin_tree_files(plugin_out: Path, outputs: dict[Path, str]) -> list[Path]:
    if not plugin_out.exists():
        return []
    expected = {path.resolve() for path in outputs}
    return sorted(
        path
        for path in plugin_out.rglob("*")
        if path.is_file() and path.resolve() not in expected
    )


def _prune_plugin_tree(plugin_out: Path, outputs: dict[Path, str]) -> None:
    for path in _extra_plugin_tree_files(plugin_out, outputs):
        path.unlink()
    if not plugin_out.exists():
        return
    for path in sorted(
        plugin_out.rglob("*"), key=lambda item: len(item.parts), reverse=True
    ):
        if not path.is_dir():
            continue
        try:
            path.rmdir()
        except OSError:
            continue


def _emit_plugin_tree(plugin_out: Path, outputs: dict[Path, str]) -> int:
    """Write every plugin-tree file deterministically."""
    _prune_plugin_tree(plugin_out, outputs)
    written = 0
    for path, content in sorted(outputs.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        written += _write_text_if_changed(path, content)
    return written


def _check_plugin_outputs(plugin_out: Path, outputs: dict[Path, str]) -> list[str]:
    failures: list[str] = []
    for path, expected in sorted(outputs.items()):
        if not path.exists():
            failures.append(f"missing plugin tree file: {path}")
            continue
        if path.read_text() != expected:
            failures.append(f"plugin tree drift: {path}")
    for path in _extra_plugin_tree_files(plugin_out, outputs):
        failures.append(f"unexpected plugin tree file: {path}")
    return failures


def _run_plugin_mode(
    args: argparse.Namespace, package_root: Path, manifest: dict
) -> int:
    skills_source_root = (
        args.skills_source_root or args.claude_skills_root or (package_root / "skills")
    )
    mcp_servers_path = args.plugin_mcp_servers or (
        package_root / "config" / "agent-workflows" / "mcp_servers.yaml"
    )
    if args.plugin_out is None:
        raise SystemExit("--mode=plugin requires --plugin-out <dest>")
    mcp_manifest = _load_mcp_servers_manifest(mcp_servers_path)
    outputs, audit_lines = _expected_plugin_outputs(
        manifest,
        mcp_manifest,
        skills_source_root,
        args.plugin_out,
        args.plugin_overrides,
        args.plugin_base_remote_sha,
        args.plugin_passthrough_lock,
    )
    stale_components: list[dict[str, object]] = []
    conflict_components: list[dict[str, object]] = []
    lock_payload = outputs.get(args.plugin_out / _PLUGIN_EFFECTIVE_LOCK)
    if lock_payload is not None:
        try:
            parsed_lock = json.loads(lock_payload)
        except json.JSONDecodeError:
            parsed_lock = {}
        stale_components = [
            entry
            for entry in parsed_lock.get("components", [])
            if isinstance(entry, dict) and entry.get("status") == "stale"
        ]
        conflict_components = [
            entry
            for entry in parsed_lock.get("components", [])
            if isinstance(entry, dict) and entry.get("status") == "merge_conflict"
        ]
    if args.check:
        failures = _check_plugin_outputs(args.plugin_out, outputs)
        if stale_components:
            print("Plugin override composition has stale overrides:", file=sys.stderr)
            for entry in stale_components:
                print(
                    "  - stale override: "
                    f"{entry.get('override_path')} {_override_digest_note(entry)}",
                    file=sys.stderr,
                )
        if conflict_components:
            print("Plugin override composition has merge conflicts:", file=sys.stderr)
            for entry in conflict_components:
                print(
                    "  - merge conflict: "
                    f"{entry.get('override_path')} {_override_digest_note(entry)}",
                    file=sys.stderr,
                )
        if failures:
            print(
                "Plugin tree is out of sync with the canonical inputs:", file=sys.stderr
            )
            for failure in failures:
                print(f"  - {failure}", file=sys.stderr)
        if failures or stale_components or conflict_components:
            return 1
        print(f"✓ plugin-tree: {len(outputs)} files match canonical inputs.")
        return 0
    written = _emit_plugin_tree(args.plugin_out, outputs)
    for line in audit_lines:
        print(line)
    if stale_components:
        for entry in stale_components:
            print(
                "warning: stale override preserved: "
                f"{entry.get('override_path')} {_override_digest_note(entry)}",
                file=sys.stderr,
            )
    if conflict_components:
        for entry in conflict_components:
            print(
                "warning: merge conflict; consumer copy preserved: "
                f"{entry.get('override_path')} {_override_digest_note(entry)}",
                file=sys.stderr,
            )
    print(f"✓ plugin-tree: wrote {written} files under {args.plugin_out}.")
    return 0


def render_plugin_tree(
    *,
    manifest_path: Path,
    skills_source_root: Path,
    mcp_servers_path: Path,
    plugin_out: Path,
    plugin_overrides: Path | None = None,
    plugin_base_remote_sha: str | None = None,
    plugin_passthrough_lock: bool = False,
) -> dict[Path, str]:
    """Single importable entry point for the plugin-tree payload (path -> content).

    implementation note S2 (pa0020-s2-build-vs-install-generation-parity): every adapter
    producer routes through the same ``_expected_plugin_outputs`` core so build
    output == install output for the same inputs —
      * the build hook / ``make generate-agent-workflows`` calls this directly
        in-process, and
      * the install-time generator in ``workbay-bootstrap`` reaches the same
        core via the subprocess CLI (``main`` -> ``_run_plugin_mode``).

    Pure: computes the output map without writing to disk, so a caller can
    render-then-decide (diff against committed, emit, or ``--check``) before
    any write lands. Materialise the returned map with ``_emit_plugin_tree``.
    """
    manifest = _load_manifest(manifest_path)
    mcp_manifest = _load_mcp_servers_manifest(mcp_servers_path)
    outputs, _audit_lines = _expected_plugin_outputs(
        manifest,
        mcp_manifest,
        skills_source_root,
        plugin_out,
        plugin_overrides,
        plugin_base_remote_sha,
        plugin_passthrough_lock,
    )
    return outputs


def _worst_status(statuses: list[int]) -> int:
    return max(statuses) if statuses else 0


def main() -> int:
    try:
        return _main()
    except ContradictoryPluginOverride as exc:
        print(f"error: {exc}", file=sys.stderr)
        return exc.code


def _main() -> int:
    args = _parse_args()
    check_statuses: list[int] = []
    if args.check_mcp_pins:
        check_statuses.append(check_mcp_pin_parity(args.manifest, args.pin_source))
        # Pin-only invocation must not load/write adapters. Other check
        # flags continue so the named gates stay combinable.
        if not (
            args.check or args.check_codex_router_blocks or args.check_coherence
        ):
            return _worst_status(check_statuses)
    manifest = _load_manifest(args.manifest)
    package_root = args.manifest.resolve().parents[2]

    if args.mode == "plugin":
        return _run_plugin_mode(args, package_root, manifest)

    # Source-of-truth: skills/<slug>/{skill.yaml, body.md}.
    # --claude-skills-root is the legacy alias kept for one release.
    skills_source_root = (
        args.skills_source_root or args.claude_skills_root or (package_root / "skills")
    )

    # Per-agent output paths. --target is sugar for "set every per-agent
    # output to this consumer repo's standard location"; explicit
    # per-agent flags still override.
    target = args.target
    claude_out = args.claude_out or (
        target / ".claude" / "commands" if target else None
    )
    claude_skills_out = args.claude_skills_out or (
        target / ".claude" / "skills" if target else None
    )
    prompts_out = args.prompts_out or (
        target / ".github" / "prompts" if target else None
    )
    codex_router_out = args.codex_router_out or (
        target.joinpath(*_GENERATED_DOCS_SUBDIR) if target else None
    )
    codex_skills_out = args.codex_skills_out or (
        target / ".codex" / "skills" if target else None
    )

    # When invoked without --target and without explicit out paths
    # (e.g. the workbay-system source-of-truth regen) the generated adapters
    # fall back to the package-internal directory that lives OUTSIDE the shipped
    # payload. implementation note S3 moved the generator under workbay_system/payload/,
    # so `package_root` now resolves to the payload tree itself — but generated
    # adapters are internal artifacts that must never land under payload (the
    # tests/test_payload_colocation.py privacy guard forbids `/generated` and the
    # wheel ships payload/ wholesale). Anchor them at the package dir two levels
    # up (payload/ -> workbay_system/ -> packages/workbay-system) so the
    # tracked docs/workbay/generated/codex-command-router.md heals in place and
    # the gitignored .github/prompts/ adapters regenerate cleanly.
    internal_root = package_root.parents[1]
    if claude_out is None:
        claude_out = internal_root / ".claude" / "commands"
    if prompts_out is None:
        prompts_out = internal_root / ".github" / "prompts"
    if codex_router_out is None:
        codex_router_out = internal_root.joinpath(*_GENERATED_DOCS_SUBDIR)

    # Legacy adapters read the same effective composition as the plugin tree:
    # a disabled skill loses its prompt and router row, and a replaced,
    # patched, or added skill reaches its prompt.
    effective = _effective_composition(
        manifest, skills_source_root, args.plugin_overrides
    )
    manifest = effective.manifest

    output_root = target.resolve() if target is not None else internal_root
    outputs = _expected_outputs(
        manifest,
        skills_source_root,
        claude_out,
        prompts_out,
        codex_router_out,
        effective,
        surface_root=output_root,
        manifest_path=args.manifest,
    )
    # Self-host (no --target) writes the package-internal router. Also
    # heal the producer checkout's root standalone router so it names a
    # path that exists from the repo root, not the consumer fallback.
    if target is None:
        producer_root = _discover_surface_root(package_root, None)
        extra_router_dir = producer_root.joinpath(*_GENERATED_DOCS_SUBDIR)
        extra_router = extra_router_dir / "codex-command-router.md"
        if (
            extra_router_dir.resolve() != Path(codex_router_out).resolve()
            and (extra_router_dir.is_dir() or extra_router.is_file())
        ):
            extra_manifest_rel, extra_generator_rel = _surface_paths(
                producer_root, args.manifest
            )
            outputs[extra_router] = _render_codex_router(
                manifest,
                manifest_rel=extra_manifest_rel,
                generator_rel=extra_generator_rel,
            )
    skill_outputs = _expected_skill_outputs(
        manifest, skills_source_root, claude_skills_out, codex_skills_out
    )

    # Search root for router consumers: --target, else the highest
    # CLAUDE.md ancestor so monorepo root + package-local docs are both
    # found. Each consumer then renders paths from *its* project root.
    repo_root = (
        target.resolve()
        if target is not None
        else _discover_surface_root(package_root, None)
    )
    hooks_outputs = _collect_hooks_outputs(package_root=package_root, target=target)

    if args.check_coherence:
        try:
            from workbay_bootstrap.coherence import main as coherence_main  # type: ignore[import-not-found]
        except ImportError as exc:
            print(
                "--check-coherence requires workbay-bootstrap to be importable",
                file=sys.stderr,
            )
            print(f"import error: {exc}", file=sys.stderr)
            check_statuses.append(1)
        else:
            check_statuses.append(int(coherence_main([str(repo_root)])))

    # A-02: --check-codex-router-blocks used to `return` unconditionally,
    # so combining it with --check silently skipped the output-drift check
    # (the second `if` was never reached). Run both when both are passed,
    # accumulating failures, and exit non-zero if either fails.
    codex_router_blocks_exit_code: int | None = None
    if args.check_codex_router_blocks:
        failures = _sync_codex_router_consumers(
            manifest, repo_root, check=True, manifest_path=args.manifest
        )
        if failures:
            print(
                "Codex router consumer docs are out of sync with the manifest:",
                file=sys.stderr,
            )
            for failure in failures:
                print(f"  - {failure}", file=sys.stderr)
            check_statuses.append(1)
        else:
            print("✓ codex-router: consumer docs match the manifest-rendered block.")
            check_statuses.append(0)

    if args.check:
        exit_code = _check_outputs(outputs, claude_out, prompts_out, codex_router_out)
        skill_failures = _check_skill_outputs(skill_outputs)
        if skill_failures:
            print(
                "Generated skill files are out of sync with the manifest:",
                file=sys.stderr,
            )
            for failure in skill_failures:
                print(f"  - {failure}", file=sys.stderr)
            exit_code = 1
        hooks_failures = [
            f"hook config drift: {path}"
            for path, expected in hooks_outputs.items()
            if not path.exists() or path.read_text() != expected
        ]
        if hooks_failures:
            print(
                "Generated hook configs are out of sync with harness-protocol.yaml:",
                file=sys.stderr,
            )
            for failure in hooks_failures:
                print(f"  - {failure}", file=sys.stderr)
            exit_code = 1
        check_statuses.append(exit_code)

    if args.check or args.check_codex_router_blocks or args.check_coherence:
        return _worst_status(check_statuses)

    total = _write_outputs(outputs)
    for stale_prompt in _extra_generated_files(prompts_out, set(outputs)):
        try:
            stale_prompt.unlink()
        except OSError:
            pass
    total += _write_outputs(hooks_outputs)
    _sync_managed_claude_settings_hooks(hooks_outputs)
    failures = _sync_codex_router_consumers(
        manifest,
        repo_root,
        check=False,
        onboard=args.onboard_router_markers,
        manifest_path=args.manifest,
    )
    if failures:
        raise SystemExit("\n".join(failures))
    total += _write_skill_files(skill_outputs)
    expected_slugs = {command["skill"] for command in _live_commands(manifest)}
    known_slugs = _shipped_skill_slugs(manifest, effective.disabled_slugs)
    _prune_stale_skill_dirs(
        claude_skills_out, expected_slugs, known_slugs, codex_skills_out
    )
    _prune_stale_skill_dirs(
        codex_skills_out, expected_slugs, known_slugs, claude_skills_out
    )
    _prune_legacy_portable_emissions(
        manifest, claude_out, claude_skills_out, codex_skills_out
    )
    print(f"✓ agent-workflows: wrote {total} adapter files.")
    return 0


