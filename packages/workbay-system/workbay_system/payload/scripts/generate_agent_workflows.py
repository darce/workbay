def _candidate_tool_python() -> str | None:
    explicit = os.environ.get("WORKBAY_TOOL_PYTHON")
    candidates: list[str] = [explicit] if explicit else []
    workbay_bin = shutil.which("workbay")
    if workbay_bin:
        try:
            first_line = Path(workbay_bin).read_text(encoding="utf-8").splitlines()[0]
        except (OSError, IndexError, UnicodeDecodeError):
            first_line = ""
        if first_line.startswith("#!") and "python" in first_line:
            candidates.append(first_line[2:])
    for candidate in candidates:
        if not candidate or candidate == sys.executable:
            continue
        try:
            probe = subprocess.run(
                [
                    candidate,
                    "-c",
                    "import workbay_system, workbay_protocol",
                ],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                timeout=5,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if probe.returncode == 0:
            return candidate
    return None


