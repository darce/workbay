    # the composition of ``manifest`` with no overrides is used.
    if effective is None:
        effective = _effective_composition(manifest, skills_source_root)
    manifest = effective.manifest
    outputs: dict[Path, str] = {}
    manifest_rel, generator_rel = _surface_paths(surface_root, manifest_path)
